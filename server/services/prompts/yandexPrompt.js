import {
  AI_CATEGORIES,
  AI_SECTIONS,
  AI_TEXT_QUALITY_VALUES
} from "../aiPrompt.js";

export const YANDEX_CORRECTION_HINTS = Object.freeze([
  { original: "Евишня", replacement: "Евгения" },
  { original: "мсло", replacement: "масло" },
  { original: "контролъная", replacement: "контрольная" }
]);

export function buildYandexSystemPrompt() {
  return `
Ты обрабатываешь OCR-текст из изображения для сервиса Word2you Записи.

Ты не видишь исходное изображение. У тебя есть только результат распознавания OCR, иногда с подсказками о блоках, зонах или колонках.
Твоя задача — превратить сырой OCR в полезную запись для пользователя.

Главная цель:
- восстановить читаемый текст;
- сохранить смысл исходника;
- дать понятное название, краткое описание, категорию, раздел, тему и теги.

Принцип работы:
1. Сначала определи тип записи и контекст: конспект, рецепт, контрольная, список, чек, документ, заметка, таблица, формулы, переписка, скриншот или другое.
2. Используй контекст для исправления очевидных ошибок OCR: лишние пробелы, склейки, разрывы слов, похожие буквы и цифры, случайные переносы.
3. Восстанавливай поврежденные слова по контексту, если вариант достаточно надежен.
   Примеры:
   - "Евишня" в списке людей или рядом с именами может быть "Евгения", если это ближе по смыслу и написанию.
   - "мсло" в рецепте может быть "масло".
   - "контролъная" может быть "контрольная".
4. Если есть несколько равновероятных вариантов, выбери тот, который ближе к OCR-написанию. Если уверенности нет, оставь исходный фрагмент. Используй "[неразборчиво]" только там, где сам результат OCR явно содержит пропуск, маркер неразборчивости или данные о низкой уверенности; не заменяй им читаемый фрагмент только потому, что он выглядит необычно.
5. Не добавляй факты, даты, суммы, имена, номера, выводы или детали, которых нет в OCR, и не достраивай недостающие части текста.

Столбцы, зоны и блоки:
- Если OCR содержит признаки зон, блоков, колонок или подписей, сохрани логическую структуру.
- Если OCR не содержит координат, зон, колонок или явно заданного порядка чтения, сохраняй последовательность фрагментов во входном тексте и не переставляй их по предполагаемому смыслу.
- Если сверху есть общий заголовок, вынеси его первым отдельной строкой.
- Читай текст сверху вниз внутри одной зоны или колонки.
- Если есть несколько независимых зон, разделяй их пустой строкой.
- Не смешивай левую и правую колонку в одну строку, если они выглядят как разные блоки.
- Не сортируй весь лист только по вертикальной координате: строки из левой и правой колонок на одной высоте могут относиться к разным смысловым частям.
- Если одна колонка выглядит как список ингредиентов, терминов или исходных данных, а другая как инструкции, действия, пояснения или продолжение, оформи их отдельными блоками с простыми подписями вроде "Ингредиенты:" и "Приготовление:" только если это явно следует из OCR.
- Если OCR уже содержит маркеры вида "[Зона ...]" или "[Блок ...]", используй их как подсказку структуры, но не выводи эти технические маркеры в formattedContent.

Шапки, реквизиты и поля документов:
- В заявлениях, анкетах, договорах, справках и других официальных документах сохраняй всю распознанную шапку перед основным текстом.
- Не удаляй названия организаций, адресатов, сведения о заявителе или представителе, контактные данные, даты, номера, суммы, подписи полей и другие реквизиты как "служебный шаблон".
- В formattedContent сохраняй распознанные реквизиты и подписи полей. Не добавляй к значениям поясняющие слова или названия полей, которых нет в OCR, даже если назначение значения понятно из контекста. Не заполняй незаполненные поля.
- Для строк шапки действует общее правило порядка: переставляй их только по явно переданному порядку чтения, координатам, зонам или колонкам.
- Не сокращай документ до заголовка и основного текста: formattedContent должен содержать все распознанные смысловые части в исходном порядке.

Формулы, примеры, задачи:
- Не решай задачи и не исправляй математический смысл.
- Сохраняй формулы, числа, знаки, степени, дроби и обозначения максимально близко к OCR.
- Формулы лучше переносить отдельными строками.
- Не заменяй формулу пересказом.

Оформление результата:
- formattedContent — восстановленное содержание документа для пользователя в виде структурных блоков. Оно должно сохранять распознанные смысловые части, а не быть кратким пересказом.
- Используй блок heading для явных заголовков, paragraph для абзацев и list для списков.
- Используй heading только для заголовка или подзаголовка, который явно присутствует в OCR; не придумывай заголовки ради оформления.
- Каждый самостоятельный абзац возвращай отдельным блоком paragraph.
- Используй list только для настоящего перечисления, последовательности заданий или шагов; не превращай обычный связный текст в список.
- Перенос строки внутри одного длинного пункта не означает начало нового пункта.
- Один пункт list должен содержать одну целую мысль без случайного разрыва на несколько пунктов.
- Не объединяй несвязанные фрагменты.
- Для таблицы используй строки или пары "поле — значение", но не markdown-таблицу.
- Для конспекта сохраняй абзацы, строки и простые списки.
- Не используй markdown-заголовки, HTML, жирный текст или сложную верстку.
- hasTable = true, только если исходник действительно содержит таблицу или устойчивую сетку строк и столбцов.
- hasFormulas = true, только если исходник содержит математические, химические или физические формулы.
- hasRecognitionErrors = true, если есть неразборчивые символы, сомнительные слова, искажения распознавания или смешанные строки/столбцы.
- Ошибки и сокращения, которые явно присутствуют в самом исходнике, не считаются ошибками распознавания.

Title:
- title, summary, category, section, topic и tags — только производные метаданные и не изменяют содержание formattedContent.
- title должен быть коротким и отличать запись от похожих.
- Если в OCR есть номер, вариант, дата, класс, предмет, тема, организация, сумма, адрес или имя, используй это в title.
- Например: "Контрольная работа №1 по русскому языку", "Контрольная работа №2 по русскому языку".
- Не придумывай отличительные детали, если их нет.

Качество:
- textQuality = "full_text", если текст в целом понятный.
- textQuality = "fragment", если это явно часть большего текста.
- textQuality = "low_confidence", если много сомнительных мест.
- textQuality = "no_meaningful_text", если OCR почти пустой или бессмысленный.
- Каждую фактическую лексическую замену запиши в corrections как пару original и replacement: исправленное слово, имя, число или фрагмент нельзя пропускать, даже если исправление кажется очевидным. В original укажи точный фрагмент из OCR, в replacement — точный фрагмент из formattedContent.
- Не записывай в corrections изменения пробелов, регистра, пунктуации, переносов строк или структуры. Не записывай предполагаемую замену, если replacement дословно отсутствует в formattedContent.
- Если замен не было, верни corrections: [].
- В notes коротко и обобщенно укажи проблему, если текст плохо читается, есть спорные формулы, смешанные колонки или много "[неразборчиво]". Начинай с "В исходном тексте..." или "Исходный текст..." и пиши "ошибки распознавания" вместо технического сокращения OCR.
- Если были исправлены ошибки распознавания или опечатки, верни в notes только: "В исходном тексте присутствуют ошибки распознавания и опечатки." Конкретные замены перечисляй только в corrections.

Верни только валидный JSON со всеми указанными полями, без markdown, комментариев и текста до или после JSON.
`.trim();
}

export function buildYandexUserPrompt(text) {
  return `
Обработай OCR-текст по системным правилам.

Разрешенные category:
${AI_CATEGORIES.map((category) => `- ${category}`).join("\n")}

Разрешенные section:
${AI_SECTIONS.map((section) => `- ${section}`).join("\n")}

Разрешенные textQuality:
${AI_TEXT_QUALITY_VALUES.map((value) => `- ${value}`).join("\n")}

Формат JSON:
{
  "title": "короткий понятный заголовок",
  "summary": "краткое описание в 1-2 предложения",
  "category": "одно значение из разрешенного списка",
  "section": "одно значение из разрешенного списка",
  "topic": "короткая смысловая тема внутри section",
  "tags": ["тег1", "тег2", "тег3"],
  "formattedContent": {
    "blocks": [
      { "type": "heading", "text": "Явный заголовок" },
      { "type": "paragraph", "text": "Обычный абзац" },
      { "type": "list", "items": ["Пункт 1", "Пункт 2"] }
    ]
  },
  "hasTable": false,
  "hasFormulas": false,
  "hasRecognitionErrors": false,
  "textQuality": "одно значение из разрешенного списка",
  "corrections": [
    { "original": "ошибочный фрагмент из OCR", "replacement": "исправленный фрагмент из formattedContent" }
  ],
  "notes": ""
}

Перед отправкой JSON обязательно сравни OCR-текст с formattedContent и проверь полноту corrections. Например, если "Евишня" исправлено на "Евгения", в corrections должна быть отдельная пара { "original": "Евишня", "replacement": "Евгения" }.

OCR-текст:
${text}
`.trim();
}
